class FavoriteFormatRule(BaseModel):
    """Flexible multi-select preference rule; values remain open-ended strings."""

    rule_id: str = Field(default_factory=lambda: uuid.uuid4().hex[:12])
    user_id: int
    name: str = "Favorite rule"
    priority: int = 0
    enabled: bool = True
    codecs: List[str] = Field(default_factory=lambda: ["any"])
    resolutions: List[str] = Field(default_factory=lambda: ["any"])
    fps_values: List[str] = Field(default_factory=lambda: ["best"])
    containers: List[str] = Field(default_factory=lambda: ["any"])

    @field_validator("codecs", "resolutions", "fps_values", "containers", mode="before")
    @classmethod
    def normalize_choices(cls, value: Any) -> List[str]:
        values = value if isinstance(value, list) else [value]
        cleaned = list(dict.fromkeys(str(item).strip().lower() for item in values if str(item).strip()))
        if "any" in cleaned:
            return ["any"]
        return cleaned or ["any"]


